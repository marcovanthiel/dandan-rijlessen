export function t(lang, key, vars) {
  const cat = M[lang] || M.zh;
  let s = cat[key] ?? M.zh[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
  return s;
}
export const TAALNAMEN = { zh: '中文', nl: 'Nederlands', en: 'English' };

// Pariteitscheck (zelfde sleutels in elke taal); aan te roepen met:
// node --input-type=module -e "import('./i18n.js').then(m=>{const r=m.pariteit();console.log(r.length?r:'i18n ok');})"
export function pariteit() {
  const basis = Object.keys(M.zh).sort();
  const fouten = [];
  for (const taal of TALEN) {
    const k = Object.keys(M[taal]).sort();
    for (const key of basis) if (!k.includes(key)) fouten.push(`${taal} mist ${key}`);
    for (const key of k) if (!basis.includes(key)) fouten.push(`${taal} heeft extra ${key}`);
  }
  return fouten;
}
